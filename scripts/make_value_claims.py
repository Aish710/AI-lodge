#!/usr/bin/env python3
"""Append (or replace) the PER-CITY value statements in docs/README-claims.md, computed from the evaluation files only, never pooled across cities:
how often the best-value hotel differed from the cheapest-rate hotel, the median and mean cost gap, the travel-time reduction against both baselines (with N), and the share
of plans the independent validator passed. Tokyo comes from docs/eval-results.json; the other cities from docs/city-eval-results.json (their own smaller samples).
docs/README-claims.md is rewritten by backend/scripts/run_evaluation.py, which drops this block: run this script again after every evaluation run.
Usage:  python scripts/make_value_claims.py [--root DIR]"""
import json
import math
import re
import sys
from pathlib import Path

START, END = "<!-- value-claims:start -->", "<!-- value-claims:end -->"
NAMES = {"tokyo": "Tokyo", "singapore": "Singapore", "seoul": "Seoul", "kuala_lumpur": "Kuala Lumpur"}
ORDER = ["tokyo", "singapore", "seoul", "kuala_lumpur"]
SAMPLE = "Seeded synthetic trips on sample data with made-up hotels; not user-tested; not a claim about real trips."


def n1(x: float) -> str:
    """One decimal, rounded DOWN (claim-safe: never rounds a benefit up, as the other generated sentences do)."""
    return f"{math.floor(x * 10) / 10:.1f}"


def city_metrics(root: Path) -> dict:
    ev = json.loads((root / "docs" / "eval-results.json").read_text(encoding="utf-8"))
    cev = json.loads((root / "docs" / "city-eval-results.json").read_text(encoding="utf-8"))
    out = {"tokyo": (ev["metrics"], "docs/eval-results.json", "JPY", "the default value of time (1,000 JPY an hour)")}
    for c, v in cev["cities"].items():
        meta = json.loads((root / "backend" / "app" / "data" / "cities" / c / "city.json").read_text(encoding="utf-8"))
        cur, default_vot = meta["currency_code"], meta["default_value_of_time_per_hour"]
        vot = "the middle tested value of time (1000 local units an hour, the same number in every currency)"
        if not default_vot / 10 <= 1000 <= default_vot * 10:
            vot += f"; note that 1000 {cur} an hour is far from this city's own default of {default_vot:,} {cur}, so this says little about how often the winner changes at a realistic value of time"
        out[c] = (v["metrics"], "docs/city-eval-results.json", cur, vot)
    return out


def sentences(city: str, m: dict, src: str, cur: str, vot_text: str) -> list[tuple[str, str]]:
    name = NAMES[city]
    h = m["hotel_value"]["vots"]["1000"]
    g = h["gap_jpy"]
    sents = [(f"value_{city}_frequency", f"{name}: the best-value hotel (lowest true cost) differed from the cheapest-rate hotel in {h['cheapest_by_rate_not_best']} of {h['n_eligible']} eligible trips at {vot_text} ({m['n_trips']} trips generated; {m['n_trips'] - h['n_eligible']} not eligible because a hotel was infeasible). {SAMPLE} Source: {src}."),
             (f"value_{city}_gap", f"{name}: when the cheapest-rate hotel was chosen, the extra true cost against the best-value hotel was a median of {g['median']:g} and a mean of {n1(g['mean'])} {cur} over {g['n']} eligible trips (maximum {g['max']:g} {cur}). {SAMPLE} Source: {src}.")]
    parts = []
    for key, label in (("naive", "an input-order baseline"), ("nn", "a nearest-neighbour baseline")):
        t = m["travel"][key]
        p = t["percent_reduction"]
        small = " (N is too small to conclude anything)" if t["n_comparable"] < 5 else ""
        parts.append(f"{n1(p['mean'])}% less than {label} (median {n1(p['median'])}%, N = {t['n_comparable']} comparable trips of {t['n_trips']}{small})")
    sents.append((f"value_{city}_travel", f"{name}: optimised routes used a mean of " + " and ".join(parts) + f" in total travel time, where both scheduled the same sights. {SAMPLE} Source: {src}."))
    v = m["validation"]["solver"]
    plans = v["n_trips"] - v["no_plan"]
    sents.append((f"value_{city}_validator", f"{name}: the independent validator passed {v['pass'] + v['pass_with_warnings']} of {plans} plans the optimiser produced and failed {v['fail']} ({v['no_plan']} of {v['n_trips']} trips had no plan because the request was infeasible). {SAMPLE} Source: {src}."))
    return sents


def block(root: Path) -> str:
    lines = [START, "", "## Per-city value statements (generated by scripts/make_value_claims.py; never pooled across cities)", ""]
    data = city_metrics(root)
    for city in ORDER:
        if city in data:
            m, src, cur, vot = data[city]
            lines += [f"- **{k}**: {s}" for k, s in sentences(city, m, src, cur, vot)]
    return "\n".join(lines + ["", END, ""])


def apply(root: Path) -> None:
    p = root / "docs" / "README-claims.md"
    text = p.read_text(encoding="utf-8")
    text = re.sub(re.escape(START) + r".*?" + re.escape(END) + r"\n?", "", text, flags=re.S).rstrip("\n") + "\n\n"
    p.write_text(text + block(root), encoding="utf-8")


if __name__ == "__main__":
    args = sys.argv[1:]
    root = Path(args[args.index("--root") + 1]) if "--root" in args else Path(__file__).resolve().parents[1]
    apply(root)
    print("value statements written to docs/README-claims.md")
