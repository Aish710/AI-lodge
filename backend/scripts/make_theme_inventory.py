"""Writes docs/design/themes-inventory.md: every distinct `category` per city with counts, the code-side mapping into themes
(frontend/src/lib/themes.json, the single source), the ambiguous cases and how they were resolved, and counts per theme per city.
Read-only on the data. Run from backend/:  python scripts/make_theme_inventory.py"""
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from app.data.loader import load_all_city_datasets  # noqa: E402

THEMES_JSON = ROOT.parent / "frontend" / "src" / "lib" / "themes.json"
OUT = ROOT.parent / "docs" / "design" / "themes-inventory.md"


def theme_of(att, cfg) -> str:
    over = cfg["overrides"].get(att.id)
    return over["theme"] if over else cfg["category"][att.category]


def render() -> str:
    cfg = json.loads(THEMES_JSON.read_text(encoding="utf-8"))
    label = {t["id"]: t["label"] for t in cfg["themes"]}
    cities = load_all_city_datasets()
    out = ["# Themes inventory (generated)", "",
           "Generated by `backend/scripts/make_theme_inventory.py` from the datasets and `frontend/src/lib/themes.json` (the single mapping the UI uses). "
           "Themes only group and filter sights in the interface; the solver never sees them. One PRIMARY theme per sight. All data is sample data.", "",
           "## Distinct `category` values per city", "", "| City | Category | Count | Sights |", "|---|---|---|---|"]
    for cid, ds in cities.items():
        by = defaultdict(list)
        for a in ds.attractions.values():
            by[a.category].append(a.name)
        for cat in sorted(by):
            out.append(f"| {ds.city.display_name} | {cat} | {len(by[cat])} | {', '.join(by[cat])} |")
    out += ["", "## Mapping: category to theme", "", "| Category | Theme |", "|---|---|"]
    out += [f"| {c} | {label[t]} |" for c, t in sorted(cfg["category"].items())]
    out += ["", "## Ambiguous cases and how they were resolved", ""]
    out += [f"- **{c}**: {n}" for c, n in cfg["category_notes"].items()]
    for aid, o in cfg["overrides"].items():
        name = next((a.name for ds in cities.values() for a in ds.attractions.values() if a.id == aid), aid)
        out.append(f"- **{name}** (override to {label[o['theme']]}): {o['why']}")
    out += ["", "## Sights per theme per city", "", "| City | " + " | ".join(label[t["id"]] for t in cfg["themes"]) + " |", "|---|" + "---|" * len(cfg["themes"])]
    for cid, ds in cities.items():
        c = Counter(theme_of(a, cfg) for a in ds.attractions.values())
        out.append(f"| {ds.city.display_name} | " + " | ".join(str(c.get(t["id"], 0)) + (" (limited)" if c.get(t["id"], 0) < cfg["limited_below"] else "") for t in cfg["themes"]) + " |")
    out += ["", f"A theme with fewer than {cfg['limited_below']} sights in a city still shows in the interface, marked \"Limited in the sample data\". Nothing is hidden and no sight is invented to fill it.", "",
            "## Each sight", "", "| City | Sight | Category | Theme |", "|---|---|---|---|"]
    for cid, ds in cities.items():
        for a in ds.attractions.values():
            out.append(f"| {ds.city.display_name} | {a.name} | {a.category} | {label[theme_of(a, cfg)]} |")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(), encoding="utf-8")
    print(f"wrote {OUT}")
