import { test, expect } from '@playwright/test'
import { planFromExample, stubTiles, watchConsole, expectClean } from './helpers.js'

for (const width of [1280, 390]) {
  test(`consumer journey at ${width}px: setup, days, sections, draft and checked AI handoff`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 })
    await stubTiles(page)
    const errors = watchConsole(page)
    await page.goto('/')
    await expect(page.getByRole('heading', { level: 1 })).toHaveText('A city break that fits you.')
    await expect(page.locator('#f-days')).toBeVisible()
    await expect(page.getByTestId('nl-panel')).toBeVisible()
    await expect(page.getByTestId('plan-trip')).toBeEnabled()
    await page.evaluate(() => window.scrollTo(0, 0))
    await page.screenshot({ path: `../docs/screenshots/redesign-plan-${width}.png`, fullPage: true })
    await page.getByTestId('choose-sights').click()
    await page.getByTestId('sight-search').fill('Senso')
    await expect(page.locator('[data-testid^="card-"]')).toHaveCount(1)
    await page.getByTestId('card-senso_ji').getByText('Must go', { exact: true }).click()
    await expect(page.getByTestId('wish-counts')).toContainText('1 must visit')
    await page.getByTestId('sight-search').fill('no such place')
    await expect(page.getByText('No matching attractions. Try another search or category.')).toBeVisible()
    await page.getByTestId('sight-search').fill('')
    await planFromExample(page)
    await expect(page.getByTestId('trip-tab-itinerary')).toHaveAttribute('aria-selected', 'true')
    await expect(page.getByTestId('daychip-1')).toHaveAttribute('aria-selected', 'true')
    await expect(page.getByTestId('day-2')).toHaveCount(0)
    await page.evaluate(() => window.scrollTo(0, 0))
    await page.screenshot({ path: `../docs/screenshots/redesign-itinerary-${width}.png`, fullPage: true })
    await page.getByTestId('daychip-2').click()
    await expect(page.getByTestId('day-2')).toBeVisible()
    if (width < 768) await page.getByRole('button', { name: 'Map', exact: true }).click()
    await expect(page.getByTestId('trip-map')).toBeVisible()
    if (width < 768) await page.getByRole('button', { name: 'Timeline', exact: true }).click()
    await page.getByTestId('edit-itinerary').click()
    await expect(page.getByTestId('ic-live')).toContainText(/Your draft/)
    const accepted = await page.getByTestId('timeline').innerText()
    const draftCount = await page.locator('[data-testid^="ic-stop-"]').count()
    const scheduled = Number((await page.getByTestId('kpi-sights').innerText()).split(' ')[0])
    expect(draftCount).toBe(scheduled)
    const first = page.locator('[data-testid^="ic-stop-"]').first()
    const move = first.getByRole('combobox')
    await move.selectOption('2')
    await expect(page.getByTestId('ic-undo')).toBeEnabled()
    await page.getByTestId('ic-undo').click()
    await page.getByTestId('ic-reset').click()
    await expect(page.locator('[data-testid^="ic-stop-"]')).toHaveCount(scheduled)
    expect(await page.getByTestId('timeline').innerText()).toBe(accepted)
    await page.getByTestId('trip-tab-costs').click()
    await expect(page.getByTestId('hotel-switch')).toBeVisible()
    await expect(page.getByTestId('cost-panel')).toBeVisible()
    await expect(page.getByTestId('timeline')).toBeHidden()
    await page.getByTestId('cash-breakdown').locator('summary').click()
    const total = await page.getByTestId('trip-cash-total').innerText()
    await expect(page.getByTestId('kpi-total')).toHaveText(total)
    await page.getByTestId('trip-tab-ai').click()
    await page.getByRole('button', { name: 'Why expensive?', exact: true }).click()
    await expect(page.getByTestId('copilot-answer')).toContainText('Illustrative room cost')
    await page.getByRole('button', { name: 'Open Trade-off Explorer', exact: true }).click()
    await expect(page.getByTestId('trip-tab-compare')).toHaveAttribute('aria-selected', 'true')
    await expect(page.getByTestId('explorer')).toBeFocused()
    await page.getByTestId('trip-tab-details').click()
    await expect(page.getByTestId('feasibility-report')).toBeVisible()
    await page.getByTestId('trip-tab-itinerary').click()
    await expect(page.getByTestId('ic-live')).toBeVisible()
    await page.getByTestId('trip-tab-itinerary').focus()
    await page.keyboard.press('ArrowRight')
    await expect(page.getByTestId('trip-tab-costs')).toBeFocused()
    await expect(page.getByRole('tabpanel', { name: 'Hotels & Costs', exact: true })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
    await page.evaluate(() => window.scrollTo(0, 0))
    await page.screenshot({ path: `../docs/screenshots/redesign-trip-${width}.png`, fullPage: true })
    const duplicates = await page.evaluate(() => {
      const ids = [...document.querySelectorAll('[id]')].map(el => el.id)
      return ids.filter((id, i) => ids.indexOf(id) !== i)
    })
    expect(duplicates).toEqual([])
    expectClean(errors)
  })
}
