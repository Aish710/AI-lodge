import { tripSection, setupSection, disclose, allDays, mapView, timelineView } from './helpers.js'
import { expect, test } from '@playwright/test'
import { expectClean, planFromExample, stubTiles, watchConsole } from './helpers.js'

test.beforeEach(async ({ page }) => { await stubTiles(page) })

test('the old Evidence and About addresses still work, with their #section, and the nav uses the new names', async ({ page }) => {
  const problems = watchConsole(page)
  await page.goto('/evidence#hotel-value')
  await expect(page).toHaveURL(/\/proof#hotel-value$/)
  await expect(page.getByRole('heading', { name: 'Proof', exact: true })).toBeVisible()
  await page.goto('/about#privacy')
  await expect(page).toHaveURL(/\/how-it-works#privacy$/)
  await expect(page.getByTestId('privacy')).toBeVisible()
  const nav = page.getByRole('navigation', { name: 'Steps' })
  await expect(nav.getByRole('link', { name: 'Proof' })).toBeVisible()
  await expect(nav.getByRole('link', { name: 'How it works' })).toBeVisible()
  await expect(nav).not.toContainText('Evidence')
  await expect(nav).not.toContainText('About')
  expectClean(problems)
})

test('the Plan screen shows the essentials first and keeps the rarely used options under a collapsed Advanced section', async ({ page }) => {
  const problems = watchConsole(page)
  await page.goto('/')
  const essentials = page.getByRole('form', { name: 'Trip essentials' })
  for (const f of ['Days', 'First day is a', 'Pace', 'Budget for sights and transport (optional)']) await expect(essentials.getByLabel(f, { exact: true })).toBeVisible()
  await expect(page.getByLabel('Value of an hour of your time', { exact: false })).toBeHidden()
  await expect(page.getByTestId('advanced')).not.toHaveAttribute('open', '')
  await expect(page.getByLabel('Allow sights with unknown opening hours')).toBeHidden()
  await page.getByTestId('advanced').getByText('Advanced options', { exact: true }).click()
  await expect(page.getByLabel('Value of an hour of your time', { exact: false })).toBeVisible()
  await expect(page.getByLabel('Allow sights with unknown opening hours')).toBeVisible()
  await expect(page.getByLabel('Set the number of nights myself')).toBeVisible()
  expectClean(problems)
})

test('hotel verdict and shared trip metrics are readable, with diagnostics in Details & Evidence', async ({ page }) => {
  const problems = watchConsole(page)
  await page.goto('/')
  await planFromExample(page)
  await allDays(page)
  await tripSection(page, 'costs')
  const verdict = page.getByTestId('verdict')
  await expect(verdict).toBeVisible()
  await expect(verdict).toContainText('Best overall among these demo hotels:')
  await expect(verdict).toContainText('not money you spend')
  await expect(verdict).not.toContainText('fictional')
  const chips = verdict.getByTestId('how-made')
  await expect(chips).toContainText('Planned by the optimiser')
  await expect(chips).toContainText('Checked by the validator')
  await expect(chips).not.toContainText('AI')
  const band = page.getByTestId('totals')
  await expect(band).toBeVisible()
  for (const label of ['Modelled cash incl. rooms', 'Estimated travel', 'Attractions scheduled', 'Active days']) await expect(band).toContainText(label)
  await expect(band.getByTestId('kpi-sights')).toHaveText(/^\d+ of \d+$/)
  await tripSection(page, 'details')
  await expect(page.getByTestId('kpi-checks')).toContainText(/\d+ of \d+ checks passed/)
  await expect(band.getByTestId('status-chip')).toContainText(/Feasible/)
  await expect(band).not.toContainText('AI')
  expectClean(problems)
})

